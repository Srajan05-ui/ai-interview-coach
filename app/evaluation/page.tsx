"use client";

import { useEffect, useState } from "react";
import Link from "next/link";

type EvaluationItem = {
  question: string;
  answer: string;
  score: number;
  feedback: string;
  strengths: string[];
  improvements: string[];
  weak_areas?: string[];
};

export default function EvaluationPage() {
  const [results, setResults] = useState<EvaluationItem[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
  const loadResults = async () => {
    const storedResults =
      localStorage.getItem("evaluationResults");

    if (storedResults) {
      try {
        const parsedResults =
          JSON.parse(storedResults);

        setTimeout(() => {
          setResults(parsedResults);
        }, 0);
      } catch (error) {
        console.error(
          "Could not read evaluation results:",
          error
        );
      }
    }

    setTimeout(() => {
      setLoading(false);
    }, 0);
  };

  loadResults();
}, []);

  if (loading) {
    return (
      <main className="min-h-screen bg-[#050816] text-white flex items-center justify-center">
        <h1 className="text-3xl font-bold">Loading evaluation...</h1>
      </main>
    );
  }

  if (results.length === 0) {
    return (
      <main className="min-h-screen bg-[#050816] text-white flex flex-col items-center justify-center p-8">
        <h1 className="text-3xl font-bold mb-4">
          No Evaluation Results Found
        </h1>

        <p className="text-gray-400 mb-6">
          Please complete an interview first.
        </p>

        <Link
          href="/interview"
          className="bg-gradient-to-r from-blue-500 to-cyan-400 px-8 py-4 rounded-2xl font-bold"
        >
          Go to Interview
        </Link>
      </main>
    );
  }

  const averageScore = Math.round(
    results.reduce((total, item) => total + Number(item.score || 0), 0) /
      results.length
  );
  const verdict =
  averageScore >= 8
    ? "Excellent Candidate"
    : averageScore >= 6
    ? "Good Candidate"
    : "Needs Improvement";

const technicalScore = Math.min(10, averageScore + 1);

const communicationScore = averageScore;

const confidenceScore = Math.min(10, averageScore + 0.5);

  const allStrengths = Array.from(
  new Set(
    results.flatMap((item) => {
      return Array.isArray(item.strengths)
        ? item.strengths
        : item.strengths
        ? [item.strengths]
        : [];
    })
  )
);

  const allImprovements = Array.from(
  new Set(
    results.flatMap((item) => {
      const improvements = Array.isArray(item.improvements)
        ? item.improvements
        : item.improvements
        ? [item.improvements]
        : [];

      const weakAreas = Array.isArray(item.weak_areas)
        ? item.weak_areas
        : item.weak_areas
        ? [item.weak_areas]
        : [];

      return [...improvements, ...weakAreas];
    })
  )
);

  return (
    <main className="min-h-screen bg-[#050816] text-white p-8 relative overflow-hidden">
      <div className="absolute top-0 left-0 h-96 w-96 rounded-full bg-blue-500/20 blur-[130px]" />
      <div className="absolute bottom-0 right-0 h-96 w-96 rounded-full bg-cyan-400/20 blur-[130px]" />

      <div className="max-w-6xl mx-auto relative z-10">
        <div className="flex justify-between items-center mb-10">
          <div>
            <h1 className="text-4xl font-bold">🧠 Evaluation Results</h1>
            <p className="text-gray-400 mt-2">
              Detailed question-wise analysis generated by MockMate AI.
            </p>
          </div>

          <Link
            href="/"
            className="bg-white/10 px-4 py-2 rounded-xl hover:bg-white/20"
          >
            ← Dashboard
          </Link>
        </div>

        <div className="grid md:grid-cols-4 gap-6 mb-8">
          <div className="bg-white/5 border border-white/10 rounded-2xl p-6">
            <p className="text-gray-400 text-sm">Overall Score</p>
            <h2 className="text-5xl font-bold text-cyan-300 mt-2">
              {averageScore}/10
            </h2>
          </div>

          <div className="bg-white/5 border border-white/10 rounded-2xl p-6">
            <p className="text-gray-400 text-sm">Questions Evaluated</p>
            <h2 className="text-5xl font-bold text-blue-400 mt-2">
              {results.length}
            </h2>
          </div>

          <div className="bg-white/5 border border-white/10 rounded-2xl p-6">
            <p className="text-gray-400 text-sm">Interview Status</p>
            <h2 className="text-3xl font-bold text-cyan-300 mt-4">
              Completed
            </h2>
          </div>
          <div className="bg-white/5 border border-white/10 rounded-2xl p-6">
  <p className="text-gray-400 text-sm">AI Verdict</p>

  <h2
    className={`text-2xl font-bold mt-4 ${
      averageScore >= 8
        ? "text-green-400"
        : averageScore >= 6
        ? "text-cyan-400"
        : "text-red-400"
    }`}
  >
    {verdict}
  </h2>
</div>
        </div>
<div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-8">
  <h2 className="text-2xl font-semibold mb-6">
    Performance Breakdown
  </h2>

  <div className="space-y-5">

    <div>
      <div className="flex justify-between mb-2">
        <span>Technical Skills</span>
        <span>{technicalScore}/10</span>
      </div>

      <div className="w-full bg-gray-700 rounded-full h-3">
        <div
          className="bg-cyan-400 h-3 rounded-full"
          style={{
            width: `${technicalScore * 10}%`,
          }}
        />
      </div>
    </div>

    <div>
      <div className="flex justify-between mb-2">
        <span>Communication</span>
        <span>{communicationScore}/10</span>
      </div>

      <div className="w-full bg-gray-700 rounded-full h-3">
        <div
          className="bg-green-400 h-3 rounded-full"
          style={{
            width: `${communicationScore * 10}%`,
          }}
        />
      </div>
    </div>

    <div>
      <div className="flex justify-between mb-2">
        <span>Confidence</span>
        <span>{confidenceScore}/10</span>
      </div>

      <div className="w-full bg-gray-700 rounded-full h-3">
        <div
          className="bg-yellow-400 h-3 rounded-full"
          style={{
            width: `${confidenceScore * 10}%`,
          }}
        />
      </div>
    </div>

  </div>
</div>
        <div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-8">
          <h2 className="text-2xl font-semibold mb-6">
            Question-wise Evaluation
          </h2>

          <div className="space-y-5">
            {results.map((item, index) => (
              <div
                key={index}
                className="bg-white/5 border border-white/10 rounded-2xl p-5"
              >
                <div className="flex justify-between gap-4 mb-3">
                  <h3 className="font-semibold">Question {index + 1}</h3>

                  <span className="text-cyan-300 font-bold">
                    {item.score}/10
                  </span>
                </div>

                <p className="text-gray-300 mb-3">{item.question}</p>
                <p className="text-gray-400 text-sm">
                  {item.feedback || "No feedback received."}
                </p>
              </div>
            ))}
          </div>
        </div>

        <div className="grid lg:grid-cols-2 gap-8 mb-8">
          <div className="bg-white/5 border border-white/10 rounded-3xl p-8">
            <h3 className="text-2xl font-semibold mb-4">
              Strength Summary
            </h3>

            {allStrengths.length > 0 ? (
              <ul className="space-y-3 text-gray-300">
                {allStrengths.map((strength, index) => (
                  <li key={index}>✅ {strength}</li>
                ))}
              </ul>
            ) : (
              <p className="text-gray-400">No strengths returned yet.</p>
            )}
          </div>

          <div className="bg-white/5 border border-white/10 rounded-3xl p-8">
            <h3 className="text-2xl font-semibold mb-4">
              Improvement Suggestions
            </h3>

            {allImprovements.length > 0 ? (
              <ul className="space-y-3 text-gray-300">
                {allImprovements.map((improvement, index) => (
                  <li key={index}>🎯 {improvement}</li>
                ))}
              </ul>
            ) : (
              <p className="text-gray-400">No improvements returned yet.</p>
            )}
          </div>
        </div>
<div className="bg-white/5 border border-white/10 rounded-3xl p-8 mb-8">
  <h2 className="text-2xl font-semibold mb-4">
    🤖 AI Recommendation
  </h2>

  <p className="text-gray-300 leading-8">
    Based on your interview performance,
    continue strengthening your technical
    concepts and communication skills.
    Focus on weak areas highlighted above
    and complete the learning roadmap to
    improve your interview readiness.
  </p>
</div>
        <div className="flex gap-4">
          <Link
            href="/results"
            className="bg-gradient-to-r from-blue-500 to-cyan-400 px-8 py-4 rounded-2xl font-bold shadow-lg shadow-cyan-500/40 hover:scale-105 transition-all"
          >
            View Final Results →
          </Link>

          <Link
            href="/learning-plan"
            className="bg-white/10 px-8 py-4 rounded-2xl font-bold hover:bg-white/20"
          >
            Generate Learning Roadmap
          </Link>
        </div>
      </div>
    </main>
  );
}
